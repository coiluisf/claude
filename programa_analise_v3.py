def calculate_rest_days(last_match_date_str):
    """Calcula dias reais de descanso desde a última partida disputada."""
    if not last_match_date_str:
        return None
    try:
        last_date = dt_datetime.strptime(last_match_date_str[:10], "%Y-%m-%d")
        today = dt_datetime.now()
        delta = (today - last_date).days
        return max(delta, 0)
    except Exception:
        return None



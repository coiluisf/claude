def calculate_advanced_ev(model_probs, odds, label_map=None):
    """
    EV = (Probabilidade_Modelo × Odd) − 1
    model_probs: dict com chaves como 'home', 'draw', 'away', 'btts', 'over25', etc.
    odds: dict com mesmas chaves (odds decimais reais)
    Retorna dict com EV por mercado e alertas.
    """
    if not model_probs or not odds:
        return None
    ev_results = {}
    alerts = []
    for key, prob in model_probs.items():
        odd = odds.get(key)
        if odd is None or odd <= 0:
            continue
        ev = (prob * odd) - 1.0
        ev_pct = ev * 100.0
        ev_results[key] = {
            "ev": round(ev, 4),
            "ev_pct": round(ev_pct, 2),
            "prob_model": round(prob * 100, 1),
            "odd": odd,
            "label": label_map.get(key, key) if label_map else key
        }
        if ev_pct > 15:
            alerts.append(f"🔥 EV ELITE +{ev_pct:.1f}% em {label_map.get(key, key) if label_map else key}")
        elif ev_pct > 10:
            alerts.append(f"✅ EV FORTE +{ev_pct:.1f}% em {label_map.get(key, key) if label_map else key}")
        elif ev_pct > 5:
            alerts.append(f"📊 EV POSITIVO +{ev_pct:.1f}% em {label_map.get(key, key) if label_map else key}")
    return {"markets": ev_results, "alerts": alerts}



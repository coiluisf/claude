# Armazena odds de abertura (primeira consulta) por fixture_id
_odds_opening_store = {}


def track_odds_movement(fixture_id, current_odds):
    """
    Registra a abertura das odds na primeira vez que é chamado para um fixture.
    Subsequentemente, calcula a variação e detecta steam moves.
    """
    global _odds_opening_store
    if not current_odds:
        return None

    fid_key = str(fixture_id)
    if fid_key not in _odds_opening_store:
        _odds_opening_store[fid_key] = {
            "home": current_odds.get("home"),
            "draw": current_odds.get("draw"),
            "away": current_odds.get("away"),
            "timestamp": str(datetime.datetime.now())
        }
        return {"status": "opening_registered", "opening": _odds_opening_store[fid_key]}

    opening = _odds_opening_store[fid_key]
    movement = {}
    alerts = []

    for side in ["home", "draw", "away"]:
        op = opening.get(side)
        cur = current_odds.get(side)
        if op and cur and op > 0:
            chg_pct = ((cur - op) / op) * 100.0
            movement[side] = {
                "opening": op,
                "current": cur,
                "change_pct": round(chg_pct, 2),
                "direction": "queda" if chg_pct < 0 else "subida"
            }
            # Steam move detection
            if chg_pct <= -30:
                alerts.append(f"🚨 MOVIMENTO EXTREMO: {side.upper()} caiu {abs(chg_pct):.1f}% — POSSÍVEL DINHEIRO PROFISSIONAL")
            elif chg_pct <= -20:
                alerts.append(f"🔴 FORTE MOVIMENTO DE MERCADO: {side.upper()} caiu {abs(chg_pct):.1f}%")
            elif chg_pct <= -10:
                alerts.append(f"🟡 MOVIMENTO RELEVANTE: {side.upper()} caiu {abs(chg_pct):.1f}%")

    return {"movement": movement, "alerts": alerts, "opening": opening}



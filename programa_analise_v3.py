def calculate_team_elo(team_id, base_elo=1500, k=32, n=20):
    """
    Calcula o ELO do time baseado nos últimos N jogos.
    Começa de 1500 e aplica fórmula ELO padrão em cada resultado.
    Retorna ELO atual e histórico.
    """
    global _elo_cache
    cache_key = str(team_id)
    if cache_key in _elo_cache:
        return _elo_cache[cache_key]

    fixtures = _get_team_fixtures_for_elo(team_id, n)
    if not fixtures:
        result = {"elo": base_elo, "history": [], "games": 0, "trend": 0.0}
        _elo_cache[cache_key] = result
        return result

    elo = float(base_elo)
    history = []

    for f in fixtures:
        is_home = int(f["teams"]["home"]["id"]) == int(team_id)
        gf = f["goals"]["home"] if is_home else f["goals"]["away"]
        gc = f["goals"]["away"] if is_home else f["goals"]["home"]

        if gf is None or gc is None:
            continue

        # Adversário começa com ELO base 1500 (sem cache do adversário para evitar recursão)
        opp_elo = 1500.0

        # Score esperado usando fórmula ELO oficial
        expected = 1.0 / (1.0 + 10.0 ** ((opp_elo - elo) / 400.0))

        # Score real: vitória=1, empate=0.5, derrota=0
        if gf > gc:
            actual = 1.0
        elif gf == gc:
            actual = 0.5
        else:
            actual = 0.0

        # Atualização com K-factor
        elo = elo + k * (actual - expected)
        history.append(round(elo, 1))

    result = {
        "elo": round(elo, 1),
        "history": history[-5:],
        "games": len(history),
        "trend": round(history[-1] - history[-3], 1) if len(history) >= 3 else 0.0
    }
    _elo_cache[cache_key] = result
    return result


def elo_win_probability(elo_home, elo_away):
    """
    Calcula probabilidades de vitória/empate/derrota baseadas no ELO.
    Usa modelo de Nate Silver (538) adaptado para futebol.
    """
    diff = elo_home - elo_away
    # Probabilidade de vitória do mandante via ELO
    p_home_win = 1.0 / (1.0 + 10.0 ** (-diff / 400.0))
    # Empate modelado como sobreposição gaussiana (aprox.)
    draw_factor = 0.22 * (1.0 - abs(diff) / 1000.0)
    draw_factor = max(0.08, min(0.30, draw_factor))
    p_draw = draw_factor
    p_home_win = p_home_win * (1.0 - draw_factor)
    p_away_win = 1.0 - p_home_win - p_draw
    return {
        "home_win": round(max(0.05, p_home_win), 4),
        "draw": round(max(0.05, p_draw), 4),
        "away_win": round(max(0.05, p_away_win), 4),
        "elo_diff": diff
    }



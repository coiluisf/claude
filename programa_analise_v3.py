def run_monte_carlo(lambda_home, lambda_away, n_simulations=100000,
                    elo_weight=0.0, xg_lambda_home=None, xg_lambda_away=None):
    """
    Simula N partidas usando Poisson ajustada com xG e ELO.
    Retorna probabilidades de vitória, empate, derrota, BTTS, Over/Under
    e os 10 placares mais frequentes.
    """
    import random as _rand
    import math as _math

    # Blend lambda: 60% Poisson base, 40% xG se disponível
    if xg_lambda_home is not None and xg_lambda_away is not None:
        lh = lambda_home * 0.60 + xg_lambda_home * 0.40
        la = lambda_away * 0.60 + xg_lambda_away * 0.40
    else:
        lh = lambda_home
        la = lambda_away

    # Ajuste por ELO: modifica lambda proporcionalmente à diferença de ELO
    if elo_weight != 0.0:
        elo_adj = 1.0 + (elo_weight * 0.001)  # elo_weight = diff em pontos
        lh = lh * max(0.85, min(1.15, elo_adj))
        la = la * max(0.85, min(1.15, 1.0 / max(0.01, elo_adj)))

    lh = max(0.1, lh)
    la = max(0.1, la)

    # Tabela cumulativa de Poisson para sampling eficiente
    def build_cdf(lam, max_goals=10):
        pmf = [(_math.exp(-lam) * (lam ** k)) / _math.factorial(k) for k in range(max_goals + 1)]
        cdf = []
        cumsum = 0.0
        for p in pmf:
            cumsum += p
            cdf.append(cumsum)
        return cdf

    def sample_poisson(cdf):
        r = _rand.random()
        for k, c in enumerate(cdf):
            if r <= c:
                return k
        return len(cdf) - 1

    cdf_h = build_cdf(lh)
    cdf_a = build_cdf(la)

    home_wins = draws = away_wins = 0
    btts = over15 = over25 = over35 = 0
    score_counts = {}

    for _ in range(n_simulations):
        hg = sample_poisson(cdf_h)
        ag = sample_poisson(cdf_a)
        if hg > ag:
            home_wins += 1
        elif hg == ag:
            draws += 1
        else:
            away_wins += 1
        if hg > 0 and ag > 0:
            btts += 1
        total = hg + ag
        if total > 1:
            over15 += 1
        if total > 2:
            over25 += 1
        if total > 3:
            over35 += 1
        key = f"{hg}x{ag}"
        score_counts[key] = score_counts.get(key, 0) + 1

    n = n_simulations
    top_scores = sorted(score_counts.items(), key=lambda x: x[1], reverse=True)[:10]

    return {
        "simulations": n,
        "home_win": round(home_wins / n, 4),
        "draw": round(draws / n, 4),
        "away_win": round(away_wins / n, 4),
        "btts": round(btts / n, 4),
        "over15": round(over15 / n, 4),
        "over25": round(over25 / n, 4),
        "over35": round(over35 / n, 4),
        "top_scores": [(s, round(c / n * 100, 2)) for s, c in top_scores],
        "lambda_used": {"home": round(lh, 3), "away": round(la, 3)}
    }



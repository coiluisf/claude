# VALIDAÇÃO E CALIBRAÇÃO DO MODELO (BACKTESTING HONESTO)
# =====================================================================
#
# Diferença importante: isto NÃO mede "confiabilidade" inventando uma
# fórmula arbitrária. Mede se as probabilidades que o modelo geraria
# para jogos PASSADOS (cujo resultado já é conhecido) foram, na média,
# consistentes com o que de fato aconteceu. Isso é a única forma honesta
# de saber se o modelo tem algum valor preditivo real.
#
# Duas métricas padrão da literatura de previsão probabilística:
#   - Brier Score: erro quadrático médio entre prob. prevista e resultado
#     real (0 = perfeito, 1 = pior possível). Para 3 desfechos (V/E/D),
#     o Brier score de um "modelo" que sempre chuta as odds de mercado
#     costuma ficar entre 0.55 e 0.65 no futebol — é a régua realista.
#   - Hit rate do favorito: quantas vezes o lado com maior probabilidade
#     prevista realmente venceu.
#
# Isso não garante lucro nem "acerto" futuro -- mercados eficientes
# tendem a já precificar a maior parte do que esse tipo de modelo capta.
# O valor real do backtest é te mostrar se o modelo é apenas RUIDO
# (Brier perto de 0.667, que é o "chute aleatório" para 3 resultados)
# ou se tem alguma calibração mínima.

def backtest_model_on_history(team_id, league_id=WORLD_CUP_LEAGUE_ID, season=WORLD_CUP_SEASON, sample_size=10):
    """Roda uma validação simplificada: para cada jogo passado do time,
    compara o resultado real com uma estimativa baseada em gols marcados/
    sofridos médios até aquele ponto (proxy simplificado do modelo Poisson).
    Retorna métricas agregadas de calibração."""
    try:
        url = f"{BASE_URL}/fixtures"
        params = {"team": team_id, "status": "FT", "last": sample_size + 5}
        res = requests.get(url, headers=headers, params=params).json()
        fixtures = res.get("response", [])
        fixtures.sort(key=lambda f: f["fixture"]["date"])  # ordem cronológica
    except Exception:
        return None

    if len(fixtures) < 6:
        return None  # amostra insuficiente para validar com seriedade

    brier_scores = []
    hits = 0
    total = 0

    rolling_gf, rolling_gc = [], []

    for f in fixtures:
        is_home = int(f["teams"]["home"]["id"]) == int(team_id)
        gf = f["goals"]["home"] if is_home else f["goals"]["away"]
        gc = f["goals"]["away"] if is_home else f["goals"]["home"]

        # Só valida a partir do 4º jogo em diante (precisa de histórico mínimo antes)
        if len(rolling_gf) >= 3:
            avg_gf = sum(rolling_gf) / len(rolling_gf)
            avg_gc = sum(rolling_gc) / len(rolling_gc)

            lam_for = max(0.3, avg_gf)
            lam_against = max(0.3, avg_gc)

            p_win = p_draw = p_loss = 0.0
            for hg in range(10):
                for ag in range(10):
                    p = poisson_probability(lam_for, hg) * poisson_probability(lam_against, ag)
                    if hg > ag: p_win += p
                    elif hg == ag: p_draw += p
                    else: p_loss += p

            _bt_sum = p_win + p_draw + p_loss
            if _bt_sum > 0:
                p_win /= _bt_sum
                p_draw /= _bt_sum
                p_loss /= _bt_sum

            if gf > gc: actual = (1, 0, 0)
            elif gf == gc: actual = (0, 1, 0)
            else: actual = (0, 0, 1)

            predicted = (p_win, p_draw, p_loss)
            brier = sum((predicted[i] - actual[i]) ** 2 for i in range(3))
            brier_scores.append(brier)

            predicted_outcome = predicted.index(max(predicted))
            actual_outcome = actual.index(1)
            if predicted_outcome == actual_outcome:
                hits += 1
            total += 1

        rolling_gf.append(gf)
        rolling_gc.append(gc)
        if len(rolling_gf) > 5:
            rolling_gf.pop(0)
            rolling_gc.pop(0)

    if total == 0:
        return None

    avg_brier = sum(brier_scores) / len(brier_scores)
    hit_rate = (hits / total) * 100

    return {
        "samples_validated": total,
        "brier_score": round(avg_brier, 3),
        "hit_rate": round(hit_rate, 1),
        "reference_random": 0.667,   # Brier de um "chute" uniforme entre V/E/D
        "reference_market": "0.55–0.65 (faixa típica de mercados eficientes)"
    }



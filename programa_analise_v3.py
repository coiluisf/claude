def get_fixture_odds(fixture_id):
    """Busca odds reais 1X2 da API. Retorna None se indisponível (jogo futuro
    demais, mercado não aberto, ou plano sem cobertura de odds)."""
    try:
        url = f"{BASE_URL}/odds"
        params = {"fixture": fixture_id, "bet": 1}  # bet=1 costuma ser o mercado "Match Winner"
        res = requests.get(url, headers=headers, params=params).json()
        response = res.get("response", [])
        if not response:
            return None

        # Percorre bookmakers até achar o mercado 1X2 com as 3 odds completas
        for bookmaker_entry in response[0].get("bookmakers", []):
            for bet in bookmaker_entry.get("bets", []):
                if bet.get("name") in ("Match Winner", "1X2"):
                    values = {v["value"]: float(v["odd"]) for v in bet.get("values", [])}
                    odd_h = values.get("Home")
                    odd_d = values.get("Draw")
                    odd_a = values.get("Away")
                    if odd_h and odd_d and odd_a:
                        return {"home": odd_h, "draw": odd_d, "away": odd_a, "bookmaker": bookmaker_entry.get("name")}
        return None
    except Exception:
        return None



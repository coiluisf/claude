def get_team_xg_history(fixtures, team_id, n=10):
    """
    Extrai xG e xGA reais de jogos passados via /fixtures/statistics.
    Retorna lista de dicts com xg e xga por jogo, mais recente primeiro.
    A API retorna 'expected_goals' como stat type quando disponível.
    Fallback: se xG não disponível, usa shots_on_target/4.5 como proxy.
    """
    import math as _math
    results = []
    for f in (fixtures or [])[:n]:
        fixture_id = f["fixture"]["id"]
        try:
            import requests as _req
            res = _req.get(
                f"{BASE_URL}/fixtures/statistics",
                headers=headers,
                params={"fixture": fixture_id}
            ).json()
            response = res.get("response", [])
            xg_val = None
            xga_val = None
            for block in response:
                is_team = int(block.get("team", {}).get("id", -1)) == int(team_id)
                for stat in block.get("statistics", []):
                    stype = stat.get("type", "")
                    sval = stat.get("value")
                    try:
                        sval_f = float(sval) if sval is not None else None
                    except (TypeError, ValueError):
                        sval_f = None
                    if is_team and stype == "expected_goals" and sval_f is not None:
                        xg_val = sval_f
                    if not is_team and stype == "expected_goals" and sval_f is not None:
                        xga_val = sval_f
            # Proxy fallback usando shots on target se xG real não disponível
            if xg_val is None or xga_val is None:
                for block in response:
                    is_team = int(block.get("team", {}).get("id", -1)) == int(team_id)
                    for stat in block.get("statistics", []):
                        stype = stat.get("type", "")
                        raw = str(stat.get("value", "0")).replace("%", "").strip()
                        v = int(raw) if raw.isdigit() else 0
                        if is_team and stype == "Shots on Goal" and xg_val is None:
                            xg_val = round(v / 4.5, 2)
                        if not is_team and stype == "Shots on Goal" and xga_val is None:
                            xga_val = round(v / 4.5, 2)
            results.append({
                "fixture_id": fixture_id,
                "xg": xg_val if xg_val is not None else 1.0,
                "xga": xga_val if xga_val is not None else 1.0,
                "proxy": xg_val is None
            })
        except Exception:
            results.append({"fixture_id": fixture_id, "xg": 1.0, "xga": 1.0, "proxy": True})
    return results


def calculate_weighted_xg(xg_history, weights=None):
    """
    Calcula xG ponderado exponencialmente.
    Jogo mais recente = 1.0, segundo = 0.80, terceiro = 0.64, quarto = 0.51, quinto = 0.41
    """
    if weights is None:
        weights = [1.0, 0.80, 0.64, 0.51, 0.41]
    if not xg_history:
        return None, None
    w_xg = 0.0
    w_xga = 0.0
    w_total = 0.0
    for i, entry in enumerate(xg_history[:len(weights)]):
        w = weights[i] if i < len(weights) else weights[-1] * (0.8 ** (i - len(weights) + 1))
        w_xg += entry["xg"] * w
        w_xga += entry["xga"] * w
        w_total += w
    if w_total == 0:
        return None, None
    return round(w_xg / w_total, 3), round(w_xga / w_total, 3)


def calculate_xg_lambdas(wxg_home, wxga_away, wxg_away, wxga_home):
    """
    Nova fórmula de lambda usando xG ponderado.
    lambda_home = 0.55 * weighted_xg_home + 0.45 * weighted_xga_away
    lambda_away = 0.55 * weighted_xg_away + 0.45 * weighted_xga_home
    """
    if None in (wxg_home, wxga_away, wxg_away, wxga_home):
        return None, None
    lh = max(0.3, 0.55 * wxg_home + 0.45 * wxga_away)
    la = max(0.3, 0.55 * wxg_away + 0.45 * wxga_home)
    return round(lh, 3), round(la, 3)



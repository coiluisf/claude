def compile_home_away_metrics(fixtures, team_id, venue):
    """
    Compila métricas separadas para jogos em casa ou fora.
    Retorna dict com médias de gols, xG proxy, escanteios, cartões, chutes, posse.
    """
    import requests as _req
    if not fixtures:
        return None
    gf_list, gc_list, corners_list, shots_list, sot_list, cards_list, poss_list = [], [], [], [], [], [], []
    for f in fixtures:
        is_home = int(f["teams"]["home"]["id"]) == int(team_id)
        gf = f["goals"]["home"] if is_home else f["goals"]["away"]
        gc = f["goals"]["away"] if is_home else f["goals"]["home"]
        gf_list.append(gf)
        gc_list.append(gc)
        try:
            sr = _req.get(
                f"{BASE_URL}/fixtures/statistics",
                headers=headers,
                params={"fixture": f["fixture"]["id"]}
            ).json().get("response", [])
            for block in sr:
                if int(block.get("team", {}).get("id", -1)) == int(team_id):
                    def _ps(bt, tp):
                        for s in bt.get("statistics", []):
                            if s["type"] == tp:
                                v = str(s.get("value", "0")).replace("%", "").strip()
                                return int(v) if v.isdigit() else 0
                        return 0
                    shots_list.append(_ps(block, "Total Shots"))
                    sot_list.append(_ps(block, "Shots on Goal"))
                    corners_list.append(_ps(block, "Corner Kicks"))
                    cards_list.append(_ps(block, "Yellow Cards") + _ps(block, "Red Cards"))
                    poss_list.append(_ps(block, "Ball Possession"))
        except Exception:
            pass

    def safe_avg(lst):
        return round(sum(lst) / len(lst), 2) if lst else 0.0

    return {
        "venue": venue,
        "n": len(fixtures),
        "avg_gf": safe_avg(gf_list),
        "avg_gc": safe_avg(gc_list),
        "avg_shots": safe_avg(shots_list),
        "avg_sot": safe_avg(sot_list),
        "avg_corners": safe_avg(corners_list),
        "avg_cards": safe_avg(cards_list),
        "avg_possession": safe_avg(poss_list) if poss_list else 50.0,
    }


def blend_home_away_general(ha_metrics, general_metrics, ha_weight=0.70):
    """
    Combina métricas casa/fora (70%) com métricas gerais (30%).
    Retorna dict com valores combinados.
    """
    if ha_metrics is None:
        return general_metrics
    gw = 1.0 - ha_weight
    fields = ["avg_gf", "avg_gc", "avg_shots", "avg_sot", "avg_corners"]
    result = {}
    for f in fields:
        ha_val = ha_metrics.get(f, 0)
        gen_val = general_metrics.get(f, general_metrics.get(f + "_calc", 0))
        result[f] = round(ha_val * ha_weight + gen_val * gw, 3)
    result["avg_possession"] = round(
        ha_metrics.get("avg_possession", 50) * ha_weight
        + general_metrics.get("avg_poss_calc", 50) * gw, 1
    )
    return result



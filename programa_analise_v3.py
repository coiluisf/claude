def calculate_ensemble_probability(poisson_probs, mc_probs, ml_probs,
                                    xg_probs, elo_probs):
    """
    Ensemble ponderado:
    Poisson = 20%, Monte Carlo = 35%, ML = 25%, xG Model = 10%, ELO = 10%
    Se ML não disponível, redistribui seu peso proporcionalmente.
    """
    weights = {
        "poisson": 0.20,
        "monte_carlo": 0.35,
        "ml": 0.25,
        "xg": 0.10,
        "elo": 0.10
    }

    sources = {
        "poisson": poisson_probs,
        "monte_carlo": mc_probs,
        "ml": ml_probs,
        "xg": xg_probs,
        "elo": elo_probs
    }

    # Remove fontes indisponíveis e redistribui pesos
    available = {k: v for k, v in sources.items() if v is not None}
    if not available:
        return None

    total_weight = sum(weights[k] for k in available)
    norm_weights = {k: weights[k] / total_weight for k in available}

    outcomes = ["home_win", "draw", "away_win"]
    ensemble = {}
    for outcome in outcomes:
        val = 0.0
        for src, probs in available.items():
            val += probs.get(outcome, 0.333) * norm_weights[src]
        ensemble[outcome] = round(val, 4)

    # Normaliza para somar 1.0
    total = sum(ensemble[o] for o in outcomes)
    if total > 0:
        for o in outcomes:
            ensemble[o] = round(ensemble[o] / total, 4)

    # BTTS ensemble
    btts_sources = [(src, probs.get("btts")) for src, probs in available.items() if probs.get("btts") is not None]
    if btts_sources:
        ensemble["btts"] = round(
            sum(p * norm_weights[src] for src, p in btts_sources) /
            sum(norm_weights[src] for src, _ in btts_sources), 4
        )

    # Over 2.5 ensemble
    over25_sources = [(src, probs.get("over25")) for src, probs in available.items() if probs.get("over25") is not None]
    if over25_sources:
        ensemble["over25"] = round(
            sum(p * norm_weights[src] for src, p in over25_sources) /
            sum(norm_weights[src] for src, _ in over25_sources), 4
        )

    ensemble["sources_used"] = list(available.keys())
    ensemble["weights_used"] = {k: round(norm_weights[k], 3) for k in available}
    return ensemble



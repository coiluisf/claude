def get_referee_stats(referee_name, season=2024, sample=20):
    """
    Busca estatísticas históricas do árbitro via /fixtures com filtro de árbitro.
    Calcula: amarelos/jogo, vermelhos/jogo, pênaltis/jogo, faltas/jogo.
    Retorna Referee Score 0-100.
    """
    import requests as _req
    if not referee_name:
        return None
    yellows, reds, games_found = [], [], 0
    try:
        res = _req.get(
            f"{BASE_URL}/fixtures",
            headers=headers,
            params={"referee": referee_name, "season": season, "status": "FT", "last": sample}
        ).json()
        fixtures = res.get("response", [])
        for f in fixtures:
            fid = f["fixture"]["id"]
            try:
                sr = _req.get(
                    f"{BASE_URL}/fixtures/statistics",
                    headers=headers,
                    params={"fixture": fid}
                ).json().get("response", [])
                yel = red = 0
                for block in sr:
                    for stat in block.get("statistics", []):
                        if stat["type"] == "Yellow Cards":
                            v = stat.get("value") or 0
                            try:
                                yel += int(v)
                            except Exception:
                                pass
                        if stat["type"] == "Red Cards":
                            v = stat.get("value") or 0
                            try:
                                red += int(v)
                            except Exception:
                                pass
                yellows.append(yel)
                reds.append(red)
                games_found += 1
            except Exception:
                continue
    except Exception:
        return None

    if games_found == 0:
        return None

    avg_y = sum(yellows) / games_found
    avg_r = sum(reds) / games_found

    # Referee Score: baseado em volume de cartões
    # Mais cartões = score mais alto (árbitro mais rigoroso)
    raw_score = (avg_y * 10) + (avg_r * 25)
    score = min(100, max(0, int(raw_score)))

    if score <= 25:
        label = "Permissivo"
    elif score <= 50:
        label = "Moderado"
    elif score <= 75:
        label = "Rigoroso"
    else:
        label = "Extremamente rigoroso"

    return {
        "referee": referee_name,
        "games_sampled": games_found,
        "avg_yellows_per_game": round(avg_y, 2),
        "avg_reds_per_game": round(avg_r, 2),
        "referee_score": score,
        "label": label
    }



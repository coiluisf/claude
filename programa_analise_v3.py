def calculate_historical_pressure_index(avg_shots, avg_sot, avg_corners,
                                         avg_dangerous_attacks=None,
                                         avg_crosses=None, avg_blocked=None):
    """
    Pressure Index pré-live calculado a partir de médias históricas.
    Fórmula proprietária escalada para 0-100.
    Dangerous attacks e crosses são opcionais (nem sempre disponíveis).
    """
    # Estimativa de dangerous attacks se não disponível: proxy = shots * 2.5
    da = avg_dangerous_attacks if avg_dangerous_attacks is not None else avg_shots * 2.5
    crosses = avg_crosses if avg_crosses is not None else avg_corners * 1.8
    blocked = avg_blocked if avg_blocked is not None else avg_sot * 0.4

    raw = (
        0.25 * avg_shots
        + 0.30 * avg_sot
        + 0.15 * avg_corners
        + 0.20 * (da / 10.0)   # normaliza dangerous attacks
        + 0.05 * (crosses / 5.0)
        + 0.05 * (blocked / 3.0)
    )

    # Escala: raw típico varia ~0-8; mapeia para 0-100
    scaled = min(100.0, max(0.0, raw * 12.5))

    if scaled <= 30:
        label = "Baixa pressão"
    elif scaled <= 60:
        label = "Pressão moderada"
    elif scaled <= 80:
        label = "Alta pressão"
    else:
        label = "Pressão extrema"

    return {"index": round(scaled, 1), "label": label, "raw": round(raw, 3)}



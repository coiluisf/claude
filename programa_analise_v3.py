def calculate_confidence_score(h_count, a_count, poisson_probs, mc_probs,
                                 real_odds, odds_movement, data_quality_score):
    """
    Confidence Score 0-100 baseado em:
    - Quantidade de amostra (30%)
    - Consistência entre modelos (25%)
    - Qualidade dos dados (20%)
    - Disponibilidade de odds (15%)
    - Movimento de mercado (10%)
    """
    # 1. Amostra
    min_games = min(h_count, a_count)
    sample_score = min(100.0, (min_games / 10.0) * 100.0)

    # 2. Consistência entre modelos (diferença entre Poisson e Monte Carlo)
    if poisson_probs and mc_probs:
        diff_home = abs(poisson_probs.get("home_win", 0.33) - mc_probs.get("home_win", 0.33))
        diff_away = abs(poisson_probs.get("away_win", 0.33) - mc_probs.get("away_win", 0.33))
        avg_diff = (diff_home + diff_away) / 2.0
        consistency_score = max(0.0, 100.0 - avg_diff * 300.0)
    else:
        consistency_score = 50.0

    # 3. Qualidade dos dados
    quality = float(data_quality_score)

    # 4. Disponibilidade de odds
    odds_score = 100.0 if real_odds else 0.0

    # 5. Movimento de mercado (alertas = menos confiança que o modelo capture info não-pública)
    if odds_movement and odds_movement.get("alerts"):
        market_score = max(20.0, 80.0 - len(odds_movement["alerts"]) * 15.0)
    else:
        market_score = 70.0

    final = (
        sample_score * 0.30
        + consistency_score * 0.25
        + quality * 0.20
        + odds_score * 0.15
        + market_score * 0.10
    )
    final = max(0.0, min(100.0, final))

    if final >= 80:
        label = "Elite"
    elif final >= 60:
        label = "Alta confiança"
    elif final >= 40:
        label = "Média confiança"
    else:
        label = "Baixa confiança"

    return {"score": round(final, 1), "label": label,
            "components": {
                "amostra": round(sample_score, 1),
                "consistencia": round(consistency_score, 1),
                "qualidade_dados": round(quality, 1),
                "odds_disponiveis": round(odds_score, 1),
                "mercado": round(market_score, 1)
            }}



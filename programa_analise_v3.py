def aggregate_player_event_history(fixtures, team_id):
    """Agrega, a partir de jogos passados reais, quais jogadores mais
    chutaram a gol e mais receberam cartão. Retorna listas ordenadas
    por frequência -- é um retrato do histórico recente, não uma
    previsão de escalação."""
    shots_counter = Counter()
    shots_on_target_counter = Counter()
    cards_counter = Counter()
    appearances = Counter()

    for f in fixtures or []:
        fixture_id = f["fixture"]["id"]
        player_data = get_fixture_player_stats(fixture_id)
        for team_block in player_data:
            if int(team_block.get("team", {}).get("id", -1)) != int(team_id):
                continue
            for p in team_block.get("players", []):
                name = p.get("player", {}).get("name", "Desconhecido")
                stats_list = p.get("statistics", [])
                if not stats_list:
                    continue
                s = stats_list[0]
                minutes = (s.get("games") or {}).get("minutes") or 0
                if not minutes:
                    continue  # não entrou em campo nesse jogo
                appearances[name] += 1

                shots = (s.get("shots") or {}).get("total") or 0
                shots_on = (s.get("shots") or {}).get("on") or 0
                yellow = (s.get("cards") or {}).get("yellow") or 0
                red = (s.get("cards") or {}).get("red") or 0

                shots_counter[name] += shots
                shots_on_target_counter[name] += shots_on
                cards_counter[name] += (yellow + red)

    return {
        "top_shooters": shots_counter.most_common(5),
        "top_shooters_on_target": shots_on_target_counter.most_common(5),
        "top_cards": cards_counter.most_common(5),
        "appearances": appearances
    }


def estimate_team_corners_by_half(team_id, fixtures, sample_size=5):
    """Busca escanteios por tempo (1º/2º) usando o parâmetro half=true
    da API, real, para os jogos recentes da equipe. Retorna médias.

    NOTA TÉCNICA: a documentação pública confirma que o parâmetro
    half=true existe e retorna dados de 1º/2º tempo, mas não documenta
    publicamente o formato exato do campo de período (pode vir como
    'statistics' duplicado com sufixo, ou como bloco 'periods' aninhado,
    dependendo da versão da API). Esta função tenta múltiplos formatos
    plausíveis de forma defensiva. Se nenhum bater, retorna None em vez
    de inventar um número -- e isso deve ser ajustado após confirmar o
    formato real na primeira chamada (consulte a resposta crua se
    precisar depurar)."""
    first_half_corners = []
    second_half_corners = []

    for f in (fixtures or [])[:sample_size]:
        fixture_id = f["fixture"]["id"]
        try:
            url = f"{BASE_URL}/fixtures/statistics"
            params = {"fixture": fixture_id, "half": "true"}
            res = requests.get(url, headers=headers, params=params).json()
            response = res.get("response", [])
            team_block = None
            for block in response:
                if int(block.get("team", {}).get("id", -1)) == int(team_id):
                    team_block = block
                    break
            if not team_block:
                continue

            fh, sh = None, None

            # Formato possível 1: bloco aninhado "periods"
            periods = team_block.get("periods")
            if periods:
                fh = (periods.get("first_half") or {}).get("Corner Kicks")
                sh = (periods.get("second_half") or {}).get("Corner Kicks")

            # Formato possível 2: lista "statistics" com campo de período explícito
            if fh is None and sh is None:
                for stat in team_block.get("statistics", []):
                    if stat.get("type") == "Corner Kicks":
                        period = stat.get("period") or stat.get("half")
                        val = stat.get("value")
                        if val is None:
                            continue
                        try:
                            val = int(val)
                        except (TypeError, ValueError):
                            continue
                        if period in ("1H", "first_half", "1st"):
                            fh = val
                        elif period in ("2H", "second_half", "2nd"):
                            sh = val

            if fh is not None:
                first_half_corners.append(fh)
            if sh is not None:
                second_half_corners.append(sh)
        except Exception:
            continue

    return {
        "first_half_avg": (sum(first_half_corners) / len(first_half_corners)) if first_half_corners else None,
        "second_half_avg": (sum(second_half_corners) / len(second_half_corners)) if second_half_corners else None,
        "samples": len(first_half_corners),
        "format_confirmed": len(first_half_corners) > 0 or len(second_half_corners) > 0
    }


def estimate_goals_by_time_window(fixtures, team_id, sample_size=10):
    """Estima, a partir de eventos reais de gol nos jogos passados, em
    quais janelas de tempo a equipe mais marca/sofre. Usa /fixtures/events."""
    windows = {"0-15": 0, "16-30": 0, "31-45": 0, "46-60": 0, "61-75": 0, "76-90+": 0}
    total_goals_found = 0

    for f in (fixtures or [])[:sample_size]:
        fixture_id = f["fixture"]["id"]
        try:
            url = f"{BASE_URL}/fixtures/events"
            params = {"fixture": fixture_id}
            res = requests.get(url, headers=headers, params=params).json()
            events = res.get("response", [])
            for ev in events:
                if ev.get("type") != "Goal":
                    continue
                if int(ev.get("team", {}).get("id", -1)) != int(team_id):
                    continue
                minute = (ev.get("time") or {}).get("elapsed")
                if minute is None:
                    continue
                total_goals_found += 1
                if minute <= 15: windows["0-15"] += 1
                elif minute <= 30: windows["16-30"] += 1
                elif minute <= 45: windows["31-45"] += 1
                elif minute <= 60: windows["46-60"] += 1
                elif minute <= 75: windows["61-75"] += 1
                else: windows["76-90+"] += 1
        except Exception:
            continue

    if total_goals_found == 0:
        return None

    return {
        "windows_pct": {k: round((v / total_goals_found) * 100, 1) for k, v in windows.items()},
        "total_goals_sampled": total_goals_found
    }


def rest_recovery_index(rest_days):
    """Converte dias de descanso num índice de recuperação física (0-100).
    Baseado em literatura esportiva geral: <3 dias = fadiga residual alta;
    5-7 dias = recuperação ótima; >10 dias = sem ganho adicional relevante."""
    if rest_days is None:
        return None
    if rest_days <= 2:
        return 55
    elif rest_days <= 4:
        return 70 + (rest_days - 2) * 7  # 70-84
    elif rest_days <= 7:
        return 85 + (rest_days - 4) * 3  # 85-94
    else:
        return min(98, 94 + (rest_days - 7))



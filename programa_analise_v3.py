def poisson_probability(lmbda, goals):
    """Calcula a probabilidade utilizando a distribuição clássica de Poisson."""
    if lmbda <= 0:
        return 1.0 if goals == 0 else 0.0
    return (math.exp(-lmbda) * (lmbda ** goals)) / math.factorial(goals)



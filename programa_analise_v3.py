def classify_team_style(metrics):
    """Classifica o perfil tático predominante de uma equipe a partir de
    médias de posse, escanteios e volume de chutes nos jogos recentes.
    Isso é uma heurística descritiva (não preditiva) para ajudar a leitura
    do confronto, como um scout faria ao assistir aos últimos jogos."""
    poss_samples = metrics.get("style_possession_samples") or []
    corner_samples = metrics.get("style_corners_samples") or []
    shots_samples = metrics.get("style_shots_samples") or []

    avg_poss = sum(poss_samples) / len(poss_samples) if poss_samples else metrics.get("avg_poss_calc", 50)
    avg_corners = sum(corner_samples) / len(corner_samples) if corner_samples else metrics.get("avg_corners_calc", 5)
    avg_shots = sum(shots_samples) / len(shots_samples) if shots_samples else metrics.get("avg_shots_calc", 12)

    # Heurística simples de classificação de perfil
    if avg_poss >= 55 and avg_shots >= 13:
        profile = "Protagonista (controla posse e volume ofensivo)"
    elif avg_poss < 45 and avg_shots >= 10:
        profile = "Contra-ataque direto (pouca posse, mas finaliza em transição)"
    elif avg_poss < 45 and avg_shots < 10:
        profile = "Retranca / Bloco baixo (cede posse e produz pouco volume)"
    else:
        profile = "Equilibrado (sem domínio claro de posse ou volume)"

    return {
        "profile": profile,
        "avg_possession": round(avg_poss, 1),
        "avg_corners": round(avg_corners, 1),
        "avg_shots": round(avg_shots, 1)
    }


def analyze_style_matchup(h_style, a_style):
    """Cruza os dois perfis para gerar uma leitura textual do confronto,
    no estilo de uma nota de scouting -- não é probabilidade, é contexto."""
    notes = []

    poss_diff = h_style["avg_possession"] - a_style["avg_possession"]
    if abs(poss_diff) >= 15:
        dominant = "mandante" if poss_diff > 0 else "visitante"
        notes.append(f"Forte assimetria de posse esperada, favorecendo o {dominant} controlar o ritmo do jogo.")
    else:
        notes.append("Disputa de posse equilibrada; o jogo tende a ser decidido em duelos individuais e transições.")

    if "Retranca" in h_style["profile"] and "Protagonista" in a_style["profile"]:
        notes.append("Mandante tende a jogar fechado e explorar contra-ataques contra um visitante que domina a posse — atenção a jogos de poucos gols com chances claras raras.")
    elif "Retranca" in a_style["profile"] and "Protagonista" in h_style["profile"]:
        notes.append("Visitante tende a se fechar; mandante pode esbarrar em bloco baixo — paciência ofensiva será decisiva.")
